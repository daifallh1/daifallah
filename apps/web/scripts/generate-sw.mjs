// Post-build: write out/sw.js with a precache list of every exported file, so the installed PWA
// (app shell, question bank and Arabic translations, which are bundled into the JS) works offline.
import { readdirSync, statSync, writeFileSync, readFileSync } from "node:fs";
import { join, relative } from "node:path";
import { createHash } from "node:crypto";

const out = new URL("../out/", import.meta.url).pathname;
const files = [];
const walk = (d) => { for (const f of readdirSync(d)) { const p = join(d, f); statSync(p).isDirectory() ? walk(p) : files.push(p); } };
walk(out);
const urls = files
  .map((p) => "/" + relative(out, p).split("\\").join("/"))
  .filter((u) => u !== "/sw.js" && !u.endsWith(".map") && !u.endsWith(".txt"))
  .map((u) => (u.endsWith("/index.html") ? u.slice(0, -"index.html".length) : u))
  .sort();
const version = createHash("sha256").update(files.filter((f) => !f.endsWith("sw.js")).map((f) => readFileSync(f)).join("")).digest("hex").slice(0, 12);
const sw = `/* generated by scripts/generate-sw.mjs */
const CACHE = "itil5-${version}";
const PRECACHE = ${JSON.stringify(urls)};
self.addEventListener("install", (e) => { e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting())); });
self.addEventListener("activate", (e) => { e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener("fetch", (e) => {
  const req = e.request;
  if (req.method !== "GET" || new URL(req.url).origin !== self.location.origin) return;
  e.respondWith((async () => {
    const cache = await caches.open(CACHE);
    const url = new URL(req.url);
    const key = req.mode === "navigate" ? (url.pathname.endsWith("/") ? url.pathname : url.pathname + "/") : req;
    const hit = await cache.match(key, { ignoreSearch: true });
    if (hit) return hit;
    try { const res = await fetch(req); if (res.ok) cache.put(req, res.clone()); return res; }
    catch { return (await cache.match("/", { ignoreSearch: true })) || Response.error(); }
  })());
});
`;
writeFileSync(join(out, "sw.js"), sw);
console.log(`sw.js: ${urls.length} precached URLs, cache itil5-${version}`);
